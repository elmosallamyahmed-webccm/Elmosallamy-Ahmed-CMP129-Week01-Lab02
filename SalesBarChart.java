public class SalesBarChart {
    public static void main(String[] args) {
        for(int i = 1; i<=10; i++){
            for(int x =1; x<=i; x++){
                System.out.print("+");
        }
        System.out.println();
        }
        for(int i = 10; i>=1; i--){
            for(int x =1; x<=i; x++){
                System.out.print("+");
        }
        System.out.println();
        }
    }
}